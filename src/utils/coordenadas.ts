const normalizar = (s: string) =>
  s.toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/\bd['\u2019]/g, 'do ')
    .replace(/[-]/g, ' ')
    .replace(/(.)\1+/g, '$1')
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

export function encontrarChaveMunicipio(nome: string): string | undefined {
  const n = nome.trim();
  const chaves = Object.keys(coordenadasMunicipiosRO);
  return chaves.find(k => k === n)
    || chaves.find(k => normalizar(k) === normalizar(n))
    || chaves.find(k => {
      const alias = aliasMunicipios[n];
      return alias ? (k === alias || normalizar(k) === normalizar(alias)) : false;
    });
}

